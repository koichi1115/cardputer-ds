#!/usr/bin/env python3
"""ILI9341 (横向き 320x240, BGR, 16bit) の panel-mipi-dbi 用初期化データを作る。
ヘッダは Cardputer 内蔵液晶の初期化データからコピーする(形式を合わせるため)。
使い方: make_init_bin.py <出力パス>
"""
import sys
REF = '/lib/firmware/cardputerzero,st7789v_lcd.bin'
hdr = open(REF, 'rb').read(16)
assert hdr[:8] == b'MIPI DBI' and hdr[15] == 1, hdr
seq = [
    (0x01, []), 'd150',                                   # soft reset
    (0x28, []),                                           # display off
    (0xCF, [0x00, 0xC1, 0x30]), (0xED, [0x64, 0x03, 0x12, 0x81]),
    (0xE8, [0x85, 0x00, 0x78]), (0xCB, [0x39, 0x2C, 0x00, 0x34, 0x02]),
    (0xF7, [0x20]), (0xEA, [0x00, 0x00]),
    (0xC0, [0x23]), (0xC1, [0x10]), (0xC5, [0x3E, 0x28]), (0xC7, [0x86]),
    (0x36, [0x28]),                                       # MADCTL: 横向き + BGR
    (0x3A, [0x55]),                                       # 16bit
    (0xB1, [0x00, 0x1B]), (0xB6, [0x08, 0x82, 0x27]), (0xF2, [0x00]), (0x26, [0x01]),
    (0xE0, [0x0F, 0x31, 0x2B, 0x0C, 0x0E, 0x08, 0x4E, 0xF1, 0x37, 0x07, 0x10, 0x03, 0x0E, 0x09, 0x00]),
    (0xE1, [0x00, 0x0E, 0x14, 0x03, 0x11, 0x07, 0x31, 0xC1, 0x48, 0x08, 0x0F, 0x0C, 0x31, 0x36, 0x0F]),
    (0x11, []), 'd120',                                   # sleep out
    (0x29, []), 'd20',                                    # display on
]
out = bytearray(hdr)
for c in seq:
    if isinstance(c, str):
        out += bytes([0x00, 1, int(c[1:])])               # 0x00 = delay(ms)
    else:
        out += bytes([c[0], len(c[1])]) + bytes(c[1])
open(sys.argv[1], 'wb').write(out)
print('init data:', sys.argv[1], len(out), 'bytes')
